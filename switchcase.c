#include <stdio.h>
void main()
	{
		int num;
		printf("enter a number:");
		scanf("%d", &num);
	switch(num){
		case 10:
			printf("good");
			break;
			case 20:
				printf("very good");
				break;
				case 30:
					printf("excellent");
					default:
						printf("invalid number");
					
	}
}
